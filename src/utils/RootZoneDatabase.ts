    public isRoot(root: string){
      return this.domainSet.has(root);
    }
  
    public getMainDomain(domain: string){
      if (!domain) return "";
      const parts = domain.split("\\.");
      let builder = "";
      for (let i = parts.length - 1; i >= 0; i--){
        const part = parts[i];
        if (this.isRoot("."+part)){
          builder = part + builder;
          builder = "." + builder;
        }
        else{
          builder = part + builder;
          break;
        }
      }
  
      return builder;
    }
